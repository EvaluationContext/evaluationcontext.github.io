"""Generate overrides/partials/series-data.html from post front matter.

Run before `zensical build`. Post templates cannot see other posts, so the
series listing on each post (overrides/partials/series.html) reads a template
variable that this script writes out: every published post with a `series:`
key, grouped by series name and ordered by date.created.

The generated file is committed so local builds work without running this,
but CI regenerates it on every deploy so it never goes stale.
"""

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
POSTS = ROOT / "docs" / "posts"
OUT = ROOT / "overrides" / "partials" / "series-data.html"

FRONT_MATTER = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)


def created(meta: dict) -> str:
    date = meta.get("date")
    if isinstance(date, dict):
        date = date.get("created")
    return str(date or "")


series: dict[str, list[dict]] = {}
for md in sorted(POSTS.rglob("*.md")):
    m = FRONT_MATTER.match(md.read_text(encoding="utf-8"))
    if not m:
        continue
    meta = yaml.safe_load(m.group(1)) or {}
    name = meta.get("series")
    if not name or meta.get("draft"):
        continue
    if not meta.get("slug"):
        sys.exit(f"{md}: series post has no slug")
    series.setdefault(str(name), []).append(
        {
            "title": str(meta.get("title", md.stem)),
            "url": str(meta["slug"]).strip("/") + "/",
            "date": created(meta),
        }
    )

for posts in series.values():
    posts.sort(key=lambda p: p["date"])

# json.dumps output is a valid MiniJinja literal
body = json.dumps(dict(sorted(series.items())), indent=2, ensure_ascii=False)
OUT.write_text(
    "{#- Generated by scripts/build_series.py. Do not edit; rerun the script. -#}\n"
    f"{{% set series_data = {body} %}}\n",
    encoding="utf-8",
)
for name, posts in series.items():
    print(f"{name}: {len(posts)} published post(s)")
print(f"wrote {OUT.relative_to(ROOT)}")
